package com.limelight.remote;

/** Windows virtual-key codes used by the remote keyboard. */
public final class Vk {
    private Vk() {}

    public static final short BACKSPACE = 0x08;
    public static final short TAB = 0x09;
    public static final short ENTER = 0x0D;
    public static final short ESC = 0x1B;
    public static final short SPACE = 0x20;
    public static final short PAGE_UP = 0x21;
    public static final short PAGE_DOWN = 0x22;
    public static final short END = 0x23;
    public static final short HOME = 0x24;
    public static final short LEFT = 0x25;
    public static final short UP = 0x26;
    public static final short RIGHT = 0x27;
    public static final short DOWN = 0x28;
    public static final short PRINT_SCREEN = 0x2C;
    public static final short INSERT = 0x2D;
    public static final short DELETE = 0x2E;
    public static final short WIN = 0x5B;
    public static final short F1 = 0x70;
    public static final short SHIFT = 0xA0;
    public static final short CTRL = 0xA2;
    public static final short ALT = 0xA4;
    public static final short OEM_COMMA = 0xBC;
    public static final short OEM_PERIOD = 0xBE;
    public static final short OEM_3 = 0xC0; // Ñ on Spanish layouts
}
